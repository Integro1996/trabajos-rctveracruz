CREATE TABLE IF NOT EXISTS trabajos_articles (
    id UUID PRIMARY KEY,
    public_reference VARCHAR(16) NULL,
    title VARCHAR(50) NOT NULL DEFAULT '',
    introduction TEXT NOT NULL,
    body_word_count INT NOT NULL DEFAULT 0,
    body_count_note TEXT NULL,
    status TEXT CHECK (status IN ('draft', 'requires_changes', 'finalized')) NOT NULL DEFAULT 'draft',
    document_key VARCHAR(128) NOT NULL,
    document_storage_path VARCHAR(512) NOT NULL,
    page_count INT NULL,
    generated_at TIMESTAMPTZ NULL,
    content_revision INT NOT NULL DEFAULT 1,
    generated_revision INT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_document_saved_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_trabajos_articles_public_reference UNIQUE (public_reference),
    CONSTRAINT uq_trabajos_articles_document_key UNIQUE (document_key)
);

CREATE TABLE IF NOT EXISTS trabajos_article_assets (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    storage_path VARCHAR(512) NOT NULL,
    mime_type VARCHAR(32) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    width INT NOT NULL,
    height INT NOT NULL,
    byte_size INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_trabajos_assets_storage_path UNIQUE (storage_path),
    CONSTRAINT fk_trabajos_assets_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_article_blocks (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    type TEXT CHECK (type IN ('text', 'figure', 'table', 'formula')) NOT NULL,
    position INT NOT NULL,
    text_content TEXT NULL,
    caption TEXT NULL,
    asset_id UUID NULL,
    table_data JSONB NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_trabajos_blocks_position UNIQUE (article_id, position),
    CONSTRAINT fk_trabajos_blocks_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE,
    CONSTRAINT fk_trabajos_blocks_asset FOREIGN KEY (asset_id) REFERENCES trabajos_article_assets(id) ON DELETE RESTRICT
  );

CREATE TABLE IF NOT EXISTS trabajos_authors (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    first_name VARCHAR(120) NOT NULL,
    last_name VARCHAR(160) NOT NULL,
    email VARCHAR(190) NOT NULL,
    institution VARCHAR(255) NOT NULL,
    orcid VARCHAR(19) NOT NULL DEFAULT '',
    is_corresponding BOOLEAN NOT NULL DEFAULT FALSE,
    position INT NOT NULL,
    CONSTRAINT uq_trabajos_authors_position UNIQUE (article_id, position),
    CONSTRAINT fk_trabajos_authors_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_keywords (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    value VARCHAR(120) NOT NULL,
    position INT NOT NULL,
    CONSTRAINT uq_trabajos_keywords_position UNIQUE (article_id, position),
    CONSTRAINT fk_trabajos_keywords_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_document_versions (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    version INT NOT NULL,
    document_key VARCHAR(128) NOT NULL,
    storage_path VARCHAR(512) NOT NULL,
    word_count INT NOT NULL DEFAULT 0,
    content_snapshot JSONB NULL,
    page_count INT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_trabajos_versions_article UNIQUE (article_id, version),
    CONSTRAINT fk_trabajos_versions_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_callbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id UUID NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    onlyoffice_status INT NULL,
    document_key VARCHAR(128) NULL,
    result VARCHAR(24) NOT NULL,
    detail TEXT NULL,
    CONSTRAINT fk_trabajos_callbacks_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_article_sessions (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    session_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    user_agent VARCHAR(500) NULL,
    ip_address VARCHAR(64) NULL,
    CONSTRAINT uq_trabajos_article_session UNIQUE (article_id, session_hash),
    CONSTRAINT fk_trabajos_article_sessions_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_recovery_credentials (
    id UUID PRIMARY KEY,
    article_id UUID NOT NULL,
    type TEXT CHECK (type IN ('HUMAN_CODE', 'QR_TOKEN', 'TEMPORARY_CODE')) NOT NULL,
    lookup_hash CHAR(64) NOT NULL,
    secret_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NULL,
    max_uses INT NULL,
    use_count INT NOT NULL DEFAULT 0,
    revoked_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_trabajos_recovery_lookup UNIQUE (lookup_hash),
    CONSTRAINT fk_trabajos_recovery_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_admin_users (
    id UUID PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(190) NOT NULL,
    password_hash TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_trabajos_admin_email UNIQUE (email)
  );

CREATE TABLE IF NOT EXISTS trabajos_admin_sessions (
    id UUID PRIMARY KEY,
    admin_id UUID NOT NULL,
    session_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    user_agent VARCHAR(500) NULL,
    ip_address VARCHAR(64) NULL,
    CONSTRAINT uq_trabajos_admin_session_hash UNIQUE (session_hash),
    CONSTRAINT fk_trabajos_admin_sessions_user FOREIGN KEY (admin_id) REFERENCES trabajos_admin_users(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_admin_document_grants (
    id UUID PRIMARY KEY,
    admin_session_id UUID NOT NULL,
    article_id UUID NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    CONSTRAINT fk_trabajos_admin_grants_session FOREIGN KEY (admin_session_id) REFERENCES trabajos_admin_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_trabajos_admin_grants_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS trabajos_admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id UUID NOT NULL,
    article_id UUID NULL,
    action VARCHAR(48) NOT NULL,
    reason TEXT NULL,
    metadata JSONB NULL,
    ip_address VARCHAR(64) NULL,
    user_agent VARCHAR(500) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_trabajos_audit_admin FOREIGN KEY (admin_id) REFERENCES trabajos_admin_users(id),
    CONSTRAINT fk_trabajos_audit_article FOREIGN KEY (article_id) REFERENCES trabajos_articles(id) ON DELETE SET NULL
  );

CREATE TABLE IF NOT EXISTS trabajos_recovery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(24) NOT NULL,
    successful BOOLEAN NOT NULL,
    rate_limited BOOLEAN NOT NULL DEFAULT FALSE,
    ip_address VARCHAR(64) NULL,
    user_agent VARCHAR(500) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

